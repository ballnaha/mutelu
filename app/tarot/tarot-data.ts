export type ZodiacElement = "Fire" | "Earth" | "Air" | "Water";

export interface ZodiacInfo {
  zodiac: string;
  element: ZodiacElement;
  elementThai: string;
  icon: string;
}

// Calculate Zodiac Element from birthdate
export function getZodiacElement(month: number, day: number): ZodiacInfo {
  if ((month === 3 && day >= 21) || (month === 4 && day <= 19))
    return { zodiac: "ราศีเมษ (Aries)", element: "Fire", elementThai: "ไฟ", icon: "🔥" };
  if ((month === 4 && day >= 20) || (month === 5 && day <= 20))
    return { zodiac: "ราศีพฤษภ (Taurus)", element: "Earth", elementThai: "ดิน", icon: "🌱" };
  if ((month === 5 && day >= 21) || (month === 6 && day <= 20))
    return { zodiac: "ราศีเมถุน (Gemini)", element: "Air", elementThai: "ลม", icon: "💨" };
  if ((month === 6 && day >= 21) || (month === 7 && day <= 22))
    return { zodiac: "ราศีกรกฎ (Cancer)", element: "Water", elementThai: "น้ำ", icon: "💧" };
  if ((month === 7 && day >= 23) || (month === 8 && day <= 22))
    return { zodiac: "ราศีสิงห์ (Leo)", element: "Fire", elementThai: "ไฟ", icon: "🔥" };
  if ((month === 8 && day >= 23) || (month === 9 && day <= 22))
    return { zodiac: "ราศีกันย์ (Virgo)", element: "Earth", elementThai: "ดิน", icon: "🌱" };
  if ((month === 9 && day >= 23) || (month === 10 && day <= 22))
    return { zodiac: "ราศีตุลย์ (Libra)", element: "Air", elementThai: "ลม", icon: "💨" };
  if ((month === 10 && day >= 23) || (month === 11 && day <= 21))
    return { zodiac: "ราศีพิจิก (Scorpio)", element: "Water", elementThai: "น้ำ", icon: "💧" };
  if ((month === 11 && day >= 22) || (month === 12 && day <= 21))
    return { zodiac: "ราศีธนู (Sagittarius)", element: "Fire", elementThai: "ไฟ", icon: "🔥" };
  if ((month === 12 && day >= 22) || (month === 1 && day <= 19))
    return { zodiac: "ราศีมังกร (Capricorn)", element: "Earth", elementThai: "ดิน", icon: "🌱" };
  if ((month === 1 && day >= 20) || (month === 2 && day <= 18))
    return { zodiac: "ราศีกุมภ์ (Aquarius)", element: "Air", elementThai: "ลม", icon: "💨" };

  return { zodiac: "ราศีมีน (Pisces)", element: "Water", elementThai: "น้ำ", icon: "💧" };
}

